// FUNZIONI DI RICERCA E CALAMITA PER HARDCORE
function hexToRgb(hex: string) {
  const h = hex.replace('#', '');
  const r = parseInt(h.substring(0, 2), 16) || 0;
  const g = parseInt(h.substring(2, 4), 16) || 0;
  const b = parseInt(h.substring(4, 6), 16) || 0;
  return { r, g, b };
}

function findClosestInArray(hex: string, array: ColorData[]): ColorData {
  const targetRgb = hexToRgb(hex);
  let closestColor = array[0];
  let minDistance = Infinity;
  for (const color of array) {
    const rgb = hexToRgb(color.hex);
    const distance = Math.sqrt(Math.pow(targetRgb.r - rgb.r, 2) + Math.pow(targetRgb.g - rgb.g, 2) + Math.pow(targetRgb.b - rgb.b, 2));
    if (distance < minDistance) { minDistance = distance; closestColor = color; }
  }
  return closestColor;
}

// Esportazioni specifiche per Hardcore
export function findMtnHardcoreSuggestions(query: string): ColorData[] {
  if (!query) return [];
  return mtnHardcoreColors.filter(c => c.name.toLowerCase().includes(query.toLowerCase()));
}

export function findMtnHardcoreByKeyword(keyword: string): ColorData | null {
  const lowerKeyword = keyword.toLowerCase();
  return mtnHardcoreColors.find(c => c.name.toLowerCase() === lowerKeyword) || 
         mtnHardcoreColors.find(c => c.name.toLowerCase().includes(lowerKeyword)) || null;
}

export function findClosestMtnHardcoreColor(hex: string): ColorData {
  return findClosestInArray(hex, mtnHardcoreColors);
}